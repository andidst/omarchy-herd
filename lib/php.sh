# PHP versions: prebuilt static-php-cli binaries, one PHP-FPM user service per version.

# Directory listing of the mirror, cached for six hours.
php_index() {
  local cache="$HERD_CACHE/php-index.json"
  if [[ ! -s $cache || -n $(find "$cache" -mmin +360 2>/dev/null) ]]; then
    curl -fsSL --max-time 30 "$HERD_PHP_MIRROR/?format=json" -o "$cache.tmp" ||
      { [[ -s $cache ]] || die "couldn't reach $HERD_PHP_MIRROR"; }
    [[ -s $cache.tmp ]] && mv "$cache.tmp" "$cache"
  fi
  cat "$cache"
}

# Latest patch release of a series that has both cli and fpm builds, e.g. 8.4 → 8.4.23.
php_latest_patch() {
  local series=$1
  php_index | jq -r --arg series "$series" '
    [.[].name | capture("^php-(?<v>\\d+\\.\\d+\\.\\d+)-(?<sapi>cli|fpm)-linux-x86_64\\.tar\\.gz$")?
      | select(.v | startswith($series + "."))]
    | group_by(.v) | map(select(length == 2) | .[0].v)
    | sort_by(split(".") | map(tonumber)) | last // empty'
}

php_installed_patch() {
  cat "$HERD_PHP_DIR/$1/VERSION" 2>/dev/null || true
}

php_installed_series() {
  local dir
  for dir in "$HERD_PHP_DIR"/*/; do
    [[ -x $dir/php ]] && basename "$dir"
  done | sort -V
}

php_write_ini() {
  local series=$1 ini_dir="$HERD_CONFIG_DIR/php/$1" timezone
  [[ -f $ini_dir/php.ini ]] && return
  mkdir -p "$ini_dir"
  timezone=$(timedatectl show -p Timezone --value 2>/dev/null || echo UTC)
  cat >"$ini_dir/php.ini" <<EOF
; PHP $series settings for omarchy-herd (CLI and PHP-FPM).
; This file is yours: omarchy-herd never overwrites it.
; Apply changes to sites with: omarchy-herd restart php-$series

memory_limit = 512M
upload_max_filesize = 128M
post_max_size = 128M
max_execution_time = 120
date.timezone = $timezone

display_errors = On
display_startup_errors = On
error_reporting = E_ALL
log_errors = On

opcache.enable = 1
opcache.enable_cli = 0
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
zend.assertions = 1

; Static builds don't know where Arch keeps its CA bundle.
openssl.cafile = /etc/ssl/certs/ca-certificates.crt
curl.cainfo = /etc/ssl/certs/ca-certificates.crt
EOF
}

php_write_fpm_conf() {
  local series=$1
  cat >"$HERD_ETC/php-fpm-$series.conf" <<EOF
; Generated by omarchy-herd. Change PHP settings in $HERD_CONFIG_DIR/php/$series/php.ini instead.
[global]
pid = $HERD_RUN/php-$series-fpm.pid
error_log = $HERD_LOG/php-$series-fpm.log
daemonize = no

[www]
listen = $(php_socket "$series")
listen.mode = 0600
pm = ondemand
pm.max_children = 16
pm.process_idle_timeout = 60s
pm.max_requests = 500
clear_env = no
catch_workers_output = yes
decorate_workers_output = no
php_admin_value[error_log] = $HERD_LOG/php-$series-errors.log
EOF
}

# Versioned commands (php8.3, php8.4…) next to the project-aware php shim.
php_write_wrapper() {
  local series=$1
  cat >"$HERD_BIN/php$series" <<EOF
#!/usr/bin/env bash
export PHPRC="$HERD_CONFIG_DIR/php/$series"
exec "$HERD_PHP_DIR/$series/php" "\$@"
EOF
  chmod +x "$HERD_BIN/php$series"
}

php_download() {
  local series=$1 patch=$2 tmp sapi
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' RETURN

  for sapi in cli fpm; do
    info "Downloading PHP $patch ($sapi)…"
    curl -fL --max-time 600 $([[ -n $HERD_JSON ]] && echo -sS || echo --progress-bar) \
      "$HERD_PHP_MIRROR/php-$patch-$sapi-linux-x86_64.tar.gz" -o "$tmp/$sapi.tar.gz" ||
      die "download of PHP $patch ($sapi) failed"
    tar -xzf "$tmp/$sapi.tar.gz" -C "$tmp" || die "couldn't unpack PHP $patch ($sapi)"
  done

  [[ -x $tmp/php && -x $tmp/php-fpm ]] || die "PHP $patch archive is missing php or php-fpm"
  "$tmp/php" -n -r 'exit(0);' || die "PHP $patch doesn't run on this machine"

  mkdir -p "$HERD_PHP_DIR/$series"
  mv -f "$tmp/php" "$tmp/php-fpm" "$HERD_PHP_DIR/$series/"
  printf '%s\n' "$patch" >"$HERD_PHP_DIR/$series/VERSION"
}

php_install() {
  local series=$1 patch
  valid_php_series "$series" || die "PHP $series isn't available (choose from ${HERD_PHP_SERIES[*]})"
  patch=$(php_latest_patch "$series")
  [[ -n $patch ]] || die "no Linux build of PHP $series found on the mirror"

  if [[ $(php_installed_patch "$series") == "$patch" ]]; then
    info "PHP $patch is already installed"
  else
    php_download "$series" "$patch"
  fi

  php_write_ini "$series"
  php_write_fpm_conf "$series"
  php_write_wrapper "$series"

  [[ -n $(config_get .php.default) ]] || config_update --arg v "$series" '.php.default = $v'

  systemctl --user daemon-reload
  systemctl --user enable "omarchy-herd-php@$series.service" >/dev/null 2>&1
  systemctl --user restart "omarchy-herd-php@$series.service"
  sites_apply
}

cmd_php() {
  local action=${1:-list}
  shift || true
  case $action in
  list | ls) php_list ;;
  available) php_available ;;
  install | add)
    [[ -n ${1:-} ]] || die "usage: omarchy-herd php install <${HERD_PHP_SERIES[*]}>"
    php_install "$1"
    ok "PHP $(php_installed_patch "$1") is installed"
    ;;
  update)
    local series updated=()
    for series in ${1:-$(php_installed_series)}; do
      [[ $(php_latest_patch "$series") == "$(php_installed_patch "$series")" ]] && continue
      php_install "$series"
      updated+=("$(php_installed_patch "$series")")
    done
    ok "${updated[*]:+Updated to PHP ${updated[*]}}${updated[*]:-PHP is up to date}"
    ;;
  uninstall | remove) php_uninstall "${1:-}" ;;
  default | use)
    local series=${1:-}
    [[ -x $HERD_PHP_DIR/$series/php ]] || die "PHP $series isn't installed; run: omarchy-herd php install $series"
    config_update --arg v "$series" '.php.default = $v'
    sites_apply
    ok "PHP $series is now the default for sites and the terminal"
    ;;
  which)
    local series
    series=$(php_for_dir "$PWD")
    ok "$series"
    ;;
  *) die "unknown php command '$action' (list, available, install, update, uninstall, default, which)" ;;
  esac
}

# Same lookup as the php shim: deepest site folder containing the directory wins.
php_for_dir() {
  local dir=$1 name
  name=$(site_for_dir "$dir")
  if [[ -n $name ]]; then site_php "$name"; else config_get .php.default; fi
}

php_uninstall() {
  local series=$1 users
  [[ -d $HERD_PHP_DIR/$series ]] || die "PHP $series isn't installed"
  [[ $(config_get .php.default) != "$series" ]] || die "PHP $series is the default; pick another default first"
  users=$(jq -r --arg v "$series" '[.isolated | to_entries[] | select(.value == $v) | .key] | join(", ")' "$HERD_CONFIG")
  [[ -z $users ]] || die "PHP $series is still used by: $users"

  systemctl --user disable --now "omarchy-herd-php@$series.service" >/dev/null 2>&1 || true
  rm -rf "${HERD_PHP_DIR:?}/$series"
  rm -f "$HERD_BIN/php$series" "$HERD_ETC/php-fpm-$series.conf"
  ok "Removed PHP $series (settings kept in $HERD_CONFIG_DIR/php/$series)"
}

php_versions_json() {
  local series default
  default=$(config_get .php.default)
  for series in $(php_installed_series); do
    jq -cn --arg series "$series" --arg patch "$(php_installed_patch "$series")" \
      --arg default "$default" --argjson running "$(json_bool user_unit_active "omarchy-herd-php@$series")" \
      --arg ini "$HERD_CONFIG_DIR/php/$series/php.ini" \
      '{version: $series, patch: $patch, default: ($series == $default), running: $running, ini: $ini}'
  done | jq -s '.'
}

php_list() {
  if [[ -n $HERD_JSON ]]; then
    php_versions_json
  else
    php_versions_json | jq -r '.[] | [.version, .patch, (if .default then "default" else "" end), (if .running then "running" else "stopped" end)] | @tsv' |
      column -t -s $'\t' -N VERSION,PATCH,DEFAULT,FPM
  fi
}

php_available() {
  local series patch list=()
  for series in "${HERD_PHP_SERIES[@]}"; do
    patch=$(php_latest_patch "$series")
    [[ -n $patch ]] || continue
    list+=("$(jq -cn --arg series "$series" --arg patch "$patch" --arg installed "$(php_installed_patch "$series")" \
      '{version: $series, latest: $patch, installed: ($installed | if . == "" then null else . end)}')")
  done
  if [[ -n $HERD_JSON ]]; then
    printf '%s\n' "${list[@]}" | jq -s '.'
  else
    printf '%s\n' "${list[@]}" | jq -r '[.version, .latest, (.installed // "-")] | @tsv' |
      column -t -s $'\t' -N VERSION,LATEST,INSTALLED
  fi
}
