# Databases and PHP-FPM run as systemd user services, so they start and stop without a password.

HERD_SERVICES=(mariadb postgres valkey)

service_name() {
  case $1 in
  mariadb) echo "MariaDB" ;;
  postgres) echo "PostgreSQL" ;;
  valkey) echo "Valkey (Redis)" ;;
  esac
}

service_port() {
  case $1 in
  mariadb) echo 3306 ;;
  postgres) echo 5432 ;;
  valkey) echo 6379 ;;
  esac
}

service_user() {
  case $1 in
  mariadb) echo root ;;
  postgres) echo postgres ;;
  esac
}

service_binary() {
  case $1 in
  mariadb) echo /usr/bin/mariadbd ;;
  postgres) echo /usr/bin/postgres ;;
  valkey) echo /usr/bin/valkey-server ;;
  esac
}

service_version() {
  case $1 in
  mariadb) /usr/bin/mariadbd --version 2>/dev/null | grep -oP 'Ver \K[0-9.]+' ;;
  postgres) /usr/bin/postgres --version 2>/dev/null | grep -oP '[0-9]+(\.[0-9]+)+' ;;
  valkey) /usr/bin/valkey-server --version 2>/dev/null | grep -oP 'v=\K[0-9.]+' ;;
  esac
}

service_unit() {
  case $1 in
  php-*) echo "omarchy-herd-php@${1#php-}.service" ;;
  *) echo "omarchy-herd-$1.service" ;;
  esac
}

write_user_units() {
  ensure_dirs

  cat >"$HERD_UNIT_DIR/omarchy-herd-php@.service" <<EOF
[Unit]
Description=omarchy-herd PHP %i (FPM)

[Service]
Type=simple
ExecStartPre=/usr/bin/mkdir -p $HERD_RUN $HERD_LOG
ExecStart=$HERD_PHP_DIR/%i/php-fpm --nodaemonize --fpm-config $HERD_ETC/php-fpm-%i.conf -c $HERD_CONFIG_DIR/php/%i/php.ini
ExecReload=/bin/kill -USR2 \$MAINPID
Restart=on-failure

[Install]
WantedBy=default.target
EOF

  cat >"$HERD_UNIT_DIR/omarchy-herd-mariadb.service" <<EOF
[Unit]
Description=omarchy-herd MariaDB

[Service]
Type=notify
ExecStartPre=/usr/bin/mkdir -p $HERD_RUN $HERD_LOG
ExecStart=/usr/bin/mariadbd --defaults-file=$HERD_ETC/mariadb.cnf
Restart=on-failure
TimeoutStartSec=120

[Install]
WantedBy=default.target
EOF

  cat >"$HERD_UNIT_DIR/omarchy-herd-postgres.service" <<EOF
[Unit]
Description=omarchy-herd PostgreSQL

[Service]
Type=notify
ExecStartPre=/usr/bin/mkdir -p $HERD_RUN $HERD_LOG
ExecStart=/usr/bin/postgres -D $HERD_DB_DIR/postgres -k $HERD_RUN -c listen_addresses=127.0.0.1 -p 5432
ExecReload=/bin/kill -HUP \$MAINPID
KillMode=mixed
KillSignal=SIGINT
Restart=on-failure
TimeoutStartSec=120

[Install]
WantedBy=default.target
EOF

  cat >"$HERD_UNIT_DIR/omarchy-herd-valkey.service" <<EOF
[Unit]
Description=omarchy-herd Valkey (Redis)

[Service]
Type=notify
ExecStartPre=/usr/bin/mkdir -p $HERD_DB_DIR/valkey $HERD_LOG
ExecStart=/usr/bin/valkey-server --bind 127.0.0.1 --port 6379 --dir $HERD_DB_DIR/valkey --supervised systemd --logfile $HERD_LOG/valkey.log
Restart=on-failure

[Install]
WantedBy=default.target
EOF

  cat >"$HERD_ETC/mariadb.cnf" <<EOF
# Generated by omarchy-herd.
[mysqld]
datadir=$HERD_DB_DIR/mariadb
socket=$HERD_RUN/mariadb.sock
pid-file=$HERD_RUN/mariadb.pid
log-error=$HERD_LOG/mariadb.log
bind-address=127.0.0.1
port=3306
character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci

[client]
socket=$HERD_RUN/mariadb.sock
EOF

  systemctl --user daemon-reload
}

# First start creates the data folder: root with an empty password, like DBngin and Herd.
service_init() {
  case $1 in
  mariadb)
    [[ -d $HERD_DB_DIR/mariadb/mysql ]] && return
    info "Creating the MariaDB data folder…"
    mkdir -p "$HERD_DB_DIR/mariadb"
    mariadb-install-db --defaults-file="$HERD_ETC/mariadb.cnf" --auth-root-authentication-method=normal \
      --skip-test-db >"$HERD_LOG/mariadb-init.log" 2>&1 ||
      die "MariaDB setup failed; see $HERD_LOG/mariadb-init.log"
    echo mariadb >"$HERD_RUN/needs-grants"
    ;;
  postgres)
    [[ -f $HERD_DB_DIR/postgres/PG_VERSION ]] && return
    info "Creating the PostgreSQL data folder…"
    initdb -D "$HERD_DB_DIR/postgres" -U postgres --auth=trust -E UTF8 --locale=C.UTF-8 \
      >"$HERD_LOG/postgres-init.log" 2>&1 || die "PostgreSQL setup failed; see $HERD_LOG/postgres-init.log"
    ;;
  valkey)
    mkdir -p "$HERD_DB_DIR/valkey"
    ;;
  esac
}

# MariaDB only knows root@localhost after install; Laravel connects over 127.0.0.1.
mariadb_grants() {
  [[ -f $HERD_RUN/needs-grants ]] || return 0
  mariadb --defaults-file="$HERD_ETC/mariadb.cnf" -uroot <<'SQL' || die "couldn't create MariaDB root users"
CREATE USER IF NOT EXISTS 'root'@'127.0.0.1' IDENTIFIED BY '';
CREATE USER IF NOT EXISTS 'root'@'::1' IDENTIFIED BY '';
GRANT ALL PRIVILEGES ON *.* TO 'root'@'127.0.0.1' WITH GRANT OPTION;
GRANT ALL PRIVILEGES ON *.* TO 'root'@'::1' WITH GRANT OPTION;
FLUSH PRIVILEGES;
SQL
  rm -f "$HERD_RUN/needs-grants"
}

service_targets() {
  local target=${1:-}
  case $target in
  all | "")
    printf '%s\n' "${HERD_SERVICES[@]}"
    php_installed_series | sed 's/^/php-/'
    ;;
  databases | dbs) printf '%s\n' "${HERD_SERVICES[@]}" ;;
  mariadb | mysql) echo mariadb ;;
  postgres | postgresql | pgsql) echo postgres ;;
  valkey | redis) echo valkey ;;
  php-*)
    php_require_installed "${target#php-}"
    echo "$target"
    ;;
  *) die "unknown service '$target' (mariadb, postgres, valkey, php-<version>, databases, all)" ;;
  esac
}

cmd_service() {
  local action=$1 target=${2:-all} id unit targets names=()
  # Assigned on its own line so a die inside service_targets stops this command.
  targets=$(service_targets "$target")
  for id in $targets; do
    unit=$(service_unit "$id")
    case $action in
    start | restart)
      if [[ $id != php-* ]]; then
        [[ -x $(service_binary "$id") ]] || die "$(service_name "$id") isn't installed; run omarchy-herd setup"
        service_init "$id"
      fi
      systemctl --user enable "$unit" >/dev/null 2>&1
      systemctl --user "$action" "$unit" || die "$id failed to start; see: omarchy-herd logs $id"
      [[ $id == mariadb ]] && mariadb_grants
      ;;
    stop)
      # Disabling too, so a stopped database stays stopped after the next login.
      systemctl --user disable --now "$unit" >/dev/null 2>&1 || true
      ;;
    esac
    names+=("$id")
  done
  case $action in
  start) ok "Started: ${names[*]}" ;;
  stop) ok "Stopped: ${names[*]}" ;;
  restart) ok "Restarted: ${names[*]}" ;;
  esac
}

services_json() {
  local id
  for id in "${HERD_SERVICES[@]}"; do
    jq -cn --arg id "$id" --arg name "$(service_name "$id")" --arg version "$(service_version "$id")" \
      --argjson port "$(service_port "$id")" --arg user "$(service_user "$id")" \
      --argjson installed "$(json_bool test -x "$(service_binary "$id")")" \
      --argjson running "$(json_bool user_unit_active "$(service_unit "$id")")" \
      --argjson enabled "$(json_bool systemctl --user is-enabled --quiet "$(service_unit "$id")")" \
      '{id: $id, name: $name, version: ($version | if . == "" then null else . end), installed: $installed,
        running: $running, enabled: $enabled, host: "127.0.0.1", port: $port,
        user: ($user | if . == "" then null else . end), password: ""}'
  done | jq -s '.'
}

cmd_services() {
  if [[ -n $HERD_JSON ]]; then
    services_json
  else
    services_json | jq -r '.[] | [.name, (if .running then "running" else "stopped" end), "127.0.0.1:\(.port)", (.user // "-"), (.version // "not installed")] | @tsv' |
      column -t -s $'\t' -N SERVICE,STATUS,ADDRESS,USER,VERSION
  fi
}

cmd_logs() {
  local id=${1:-} file
  case $id in
  caddy) file=$HERD_LOG/caddy.log ;;
  mariadb | mysql) file=$HERD_LOG/mariadb.log ;;
  valkey | redis) file=$HERD_LOG/valkey.log ;;
  postgres) exec journalctl --user -u omarchy-herd-postgres -n 200 -f ;;
  php-*) file=$HERD_LOG/php-${id#php-}-errors.log ;;
  "") die "usage: omarchy-herd logs <caddy|mariadb|postgres|valkey|php-<version>|site-name>" ;;
  *) file=$HERD_LOG/sites/$id.log ;;
  esac
  [[ -f $file ]] || die "no log yet at $file"
  exec tail -n 200 -f "$file"
}
