# Sites: parked folders, links, proxies, per-site PHP, and the generated Caddyfile.

SEP=$'\x1f'

# One record per site: name, path, source (link|proxy|parked), proxy target.
# Links and proxies win over parked folders with the same name.
site_records() {
  local name path target dir sub
  local -A seen=()

  while IFS=$'\t' read -r name path; do
    [[ -n $name ]] || continue
    seen[$name]=1
    printf '%s\n' "$name$SEP$path${SEP}link$SEP"
  done < <(jq -r '.links | to_entries[] | [.key, .value] | @tsv' "$HERD_CONFIG")

  while IFS=$'\t' read -r name target; do
    [[ -n $name && -z ${seen[$name]:-} ]] || continue
    seen[$name]=1
    printf '%s\n' "$name$SEP${SEP}proxy$SEP$target"
  done < <(jq -r '.proxies | to_entries[] | [.key, .value] | @tsv' "$HERD_CONFIG")

  while IFS= read -r dir; do
    [[ -d $dir ]] || continue
    for sub in "$dir"/*/; do
      [[ -d $sub ]] || continue
      sub=${sub%/}
      name=$(slugify "${sub##*/}")
      [[ -n $name && -z ${seen[$name]:-} ]] || continue
      valid_path "$sub" || continue
      seen[$name]=1
      printf '%s\n' "$name$SEP$sub${SEP}parked$SEP"
    done
  done < <(jq -r '.parked[]' "$HERD_CONFIG")
}

site_type() {
  local path=$1
  if [[ -f $path/artisan ]]; then echo laravel
  elif [[ -f $path/composer.json || -f $path/index.php || -f $path/public/index.php ]]; then echo php
  elif [[ -f $path/package.json ]]; then echo node
  elif [[ -f $path/index.html || -f $path/public/index.html ]]; then echo static
  else echo unknown
  fi
}

site_docroot() {
  if [[ -d $1/public ]]; then echo "$1/public"; else echo "$1"; fi
}

site_php() {
  local name=$1 version
  version=$(jq -r --arg name "$name" '.isolated[$name] // empty' "$HERD_CONFIG")
  printf '%s' "${version:-$(config_get .php.default)}"
}

# Find the site whose folder contains the given directory (deepest match wins).
site_for_dir() {
  local dir=$1 best="" best_len=0 name path source target
  while IFS=$SEP read -r name path source target; do
    [[ -n $path ]] || continue
    if [[ $dir == "$path" || $dir == "$path"/* ]] && ((${#path} > best_len)); then
      best=$name
      best_len=${#path}
    fi
  done < <(site_records)
  printf '%s' "$best"
}

site_path() {
  local want=$1 name path source target
  while IFS=$SEP read -r name path source target; do
    [[ $name == "$want" ]] && { printf '%s' "$path"; return 0; }
  done < <(site_records)
  return 1
}

# Resolve the site argument, falling back to the site that contains $PWD.
resolve_site() {
  local name=${1:-}
  if [[ -z $name ]]; then
    name=$(site_for_dir "$PWD")
    [[ -n $name ]] || die "$PWD isn't inside a parked or linked site; pass a site name"
  fi
  # Not grep -q: exiting early would SIGPIPE the producer and fail the pipeline under pipefail.
  site_records | cut -d "$SEP" -f1 | grep -xF -- "$name" >/dev/null || die "no site named '$name'"
  printf '%s' "$name"
}

sites_json() {
  local with_node=${1:-} name path source target type docroot php node installed
  local default_php tld_name
  default_php=$(config_get .php.default)
  tld_name=$(tld)

  while IFS=$SEP read -r name path source target; do
    type="" docroot="" php="" node="" installed=""
    if [[ $source != proxy ]]; then
      type=$(site_type "$path")
      docroot=$(site_docroot "$path")
      php=$(site_php "$name")
      [[ -n $php && -x $HERD_PHP_DIR/$php/php ]] && installed=1
      [[ -n $with_node ]] && node=$(mise current node -C "$path" 2>/dev/null | head -1 || true)
    fi
    printf '%s\n' "$name$SEP$path$SEP$source$SEP$target$SEP$type$SEP$docroot$SEP$php$SEP$node$SEP$installed"
  done < <(site_records) | jq -R -s \
    --arg tld "$tld_name" \
    --arg default_php "$default_php" \
    --slurpfile config "$HERD_CONFIG" '
      def nz: if . == "" then null else . end;
      split("\n") | map(select(length > 0) | split("\u001f") | {
        name: .[0],
        domain: "\(.[0]).\($tld)",
        url: "https://\(.[0]).\($tld)",
        path: (.[1] | nz),
        source: .[2],
        proxy: (.[3] | nz),
        type: (if .[2] == "proxy" then "proxy" else .[4] end),
        docroot: (.[5] | nz),
        php: (.[6] | nz),
        php_installed: (.[8] == "1"),
        isolated: ($config[0].isolated[.[0]] != null),
        node: (.[7] | nz)
      }) | sort_by(.name)'
}

php_socket() {
  printf '%s' "$HERD_RUN/php-$1.sock"
}

# Write the Caddyfile and the path→PHP map used by the php shim, then reload Caddy.
sites_apply() {
  local name path source target php tmp tld_name default_php php_map series
  tld_name=$(tld)
  default_php=$(config_get .php.default)
  tmp=$(mktemp "$HERD_CADDYFILE.XXXXXX")
  HERD_CLEANUP+=("$tmp")

  {
    cat <<EOF
# Generated by omarchy-herd. Edits are overwritten; change sites with omarchy-herd instead.
{
	admin $HERD_CADDY_ADMIN
	persist_config off
	local_certs
	skip_install_trust
	auto_https disable_redirects
	default_bind 127.0.0.1 [::1]
	log {
		output file "$HERD_LOG/caddy.log"
	}
}
EOF
    while IFS=$SEP read -r name path source target; do
      printf '\nhttp://%s.%s, https://%s.%s {\n' "$name" "$tld_name" "$name" "$tld_name"
      if [[ $source == proxy ]]; then
        printf '\treverse_proxy %s\n' "$target"
      else
        php=$(site_php "$name")
        printf '\troot * "%s"\n' "$(site_docroot "$path")"
        # Never serve .env, .git and other dotfiles from project roots without a public/ folder.
        printf '\t@hidden {\n\t\tpath */.*\n\t\tnot path /.well-known/*\n\t}\n\trespond @hidden 404\n'
        printf '\tencode zstd gzip\n'
        [[ -n $php ]] && printf '\tphp_fastcgi unix/%s\n' "$(php_socket "$php")"
        printf '\tfile_server\n'
        printf '\tlog {\n\t\toutput file "%s/sites/%s.log"\n\t}\n' "$HERD_LOG" "$name"
      fi
      printf '}\n'
    done < <(site_records)
  } >"$tmp"

  mkdir -p "$HERD_LOG/sites"
  mv "$tmp" "$HERD_CADDYFILE"

  # Built in full before writing, so a failure halfway never replaces a good map.
  php_map=$(
    printf 'default\t%s\n' "$default_php"
    while IFS=$SEP read -r name path source target; do
      [[ $source == proxy ]] && continue
      printf '%s\t%s\n' "$path" "$(site_php "$name")"
    done < <(site_records)
  )
  write_atomic "$HERD_ETC/php-map" <<<"$php_map"

  # Every installed PHP version a site points at must be running, or that site returns 502.
  while IFS= read -r series; do
    [[ -n $series && -x $HERD_PHP_DIR/$series/php ]] && php_ensure_running "$series"
  done < <(cut -f2 <<<"$php_map" | sort -u)

  caddy_reload
  watch_apply
}

# A systemd path unit re-runs `apply` when a folder appears in or leaves a parked
# directory, so a freshly cloned project gets its .test domain without any command.
watch_apply() {
  local path_unit="$HERD_UNIT_DIR/omarchy-herd-watch.path" dir watched=() content
  while IFS= read -r dir; do
    [[ -d $dir ]] && watched+=("PathChanged=${dir//%/%%}")
  done < <(jq -r '.parked[]' "$HERD_CONFIG")

  if ((${#watched[@]} == 0)); then
    [[ -f $path_unit ]] || return 0
    systemctl --user disable --now omarchy-herd-watch.path >/dev/null 2>&1 || true
    rm -f "$path_unit" "$HERD_UNIT_DIR/omarchy-herd-watch.service"
    systemctl --user daemon-reload
    return 0
  fi

  local service_unit="$HERD_UNIT_DIR/omarchy-herd-watch.service" service
  content=$(printf '%s\n' "[Unit]" "Description=omarchy-herd: notice new folders in parked directories" "" "[Path]" \
    "${watched[@]}" "Unit=omarchy-herd-watch.service" "" "[Install]" "WantedBy=default.target")
  service=$(printf '%s\n' "[Unit]" "Description=omarchy-herd: refresh sites after parked folders change" "" \
    "[Service]" "Type=oneshot" "ExecStart=\"${HERD_ROOT//%/%%}/bin/omarchy-herd\" apply")

  # Skip only when both files are current and the watcher is actually running.
  if [[ -f $path_unit && $(<"$path_unit") == "$content" && -f $service_unit && $(<"$service_unit") == "$service" ]] &&
    user_unit_active omarchy-herd-watch.path; then
    return 0
  fi

  printf '%s\n' "$content" >"$path_unit"
  printf '%s\n' "$service" >"$service_unit"
  systemctl --user daemon-reload
  systemctl --user enable omarchy-herd-watch.path >/dev/null 2>&1
  systemctl --user restart omarchy-herd-watch.path
}

caddy_reload() {
  system_unit_active omarchy-herd-caddy || return 0
  caddy reload --config "$HERD_CADDYFILE" --adapter caddyfile --address "$HERD_CADDY_ADMIN" >/dev/null 2>"$HERD_RUN/caddy-reload.err" ||
    die "Caddy rejected the new config: $(tail -3 "$HERD_RUN/caddy-reload.err")"
}

cmd_park() {
  local dir
  dir=$(readlink -f -- "${1:-$PWD}")
  [[ -d $dir ]] || die "$dir isn't a folder"
  servable_dir "$dir"
  config_update --arg dir "$dir" '.parked = (.parked + [$dir] | unique)'
  sites_apply
  ok "Parked $dir: every folder inside is now <folder>.$(tld)"
}

cmd_unpark() {
  local dir
  dir=$(readlink -f -- "${1:-$PWD}")
  config_update --arg dir "$dir" '.parked -= [$dir]'
  sites_apply
  ok "Unparked $dir"
}

cmd_link() {
  local name=${1:-} dir
  dir=$(readlink -f -- "${2:-$PWD}")
  [[ -d $dir ]] || die "$dir isn't a folder"
  servable_dir "$dir"
  name=$(slugify "${name:-${dir##*/}}")
  valid_site_name "$name" || die "'$name' isn't a valid site name"
  config_update --arg name "$name" --arg dir "$dir" '.links[$name] = $dir | del(.proxies[$name])'
  sites_apply
  ok "Linked https://$name.$(tld) → $dir"
}

cmd_unlink() {
  local name=${1:-}
  [[ -n $name ]] || name=$(slugify "${PWD##*/}")
  jq -e --arg name "$name" '.links[$name]' "$HERD_CONFIG" >/dev/null || die "no linked site named '$name'"
  config_update --arg name "$name" 'del(.links[$name]) | del(.isolated[$name])'
  sites_apply
  ok "Unlinked $name.$(tld)"
}

cmd_proxy() {
  local name=${1:-} target=${2:-}
  name=$(slugify "$name")
  valid_site_name "$name" || die "usage: omarchy-herd proxy <name> <port|host:port>"
  [[ $target =~ ^[0-9]+$ ]] && target="127.0.0.1:$target"
  [[ $target =~ ^(https?://)?[A-Za-z0-9.-]+:[0-9]+$ ]] || die "proxy target must be a port or host:port"
  config_update --arg name "$name" --arg target "$target" '.proxies[$name] = $target | del(.links[$name])'
  sites_apply
  ok "Proxying https://$name.$(tld) → $target"
}

cmd_unproxy() {
  local name=${1:-}
  jq -e --arg name "$name" '.proxies[$name]' "$HERD_CONFIG" >/dev/null || die "no proxy named '$name'"
  config_update --arg name "$name" 'del(.proxies[$name])'
  sites_apply
  ok "Removed proxy $name.$(tld)"
}

cmd_isolate() {
  local version=${1:-} name
  [[ -n $version ]] || die "usage: omarchy-herd isolate <php-version> [site]"
  php_require_installed "$version"
  name=$(resolve_site "${2:-}")
  php_ensure_running "$version"
  config_update --arg name "$name" --arg version "$version" '.isolated[$name] = $version'
  sites_apply
  ok "$name.$(tld) now uses PHP $version"
}

cmd_unisolate() {
  local name
  name=$(resolve_site "${1:-}")
  config_update --arg name "$name" 'del(.isolated[$name])'
  sites_apply
  ok "$name.$(tld) now uses the default PHP ($(config_get .php.default))"
}

cmd_sites() {
  if [[ -n $HERD_JSON ]]; then
    sites_json with-node
  else
    sites_json with-node | jq -r '.[] | [.domain, .type, (.php // .proxy // "-"), (.node // "-"), (.path // "")] | @tsv' |
      column -t -s $'\t' -N SITE,TYPE,PHP/PROXY,NODE,PATH
  fi
}

cmd_open() {
  local name
  name=$(resolve_site "${1:-}")
  # 3>&- too: the browser mustn't keep our real stdout open, or callers wait on it.
  xdg-open "https://$name.$(tld)" >/dev/null 2>&1 3>&- &
  ok "Opening https://$name.$(tld)"
}
